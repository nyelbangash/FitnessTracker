export const themeIds = Object.keys(themes);

export const themeGroups = themeIds.reduce((acc, id) => {
  const group = themes[id].group;
  acc[group] = acc[group] || [];
  acc[group].push(id);
  return acc;
}, {});

export const defaultThemeId = "paper";

export function getTheme(id) {
  return themes[id] || themes[defaultThemeId];
}
